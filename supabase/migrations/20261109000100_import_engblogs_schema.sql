create table public.engblogs_links (
 id bigint generated by default as identity primary key,
 created_at timestamptz default now(), company text unique, link text, logo_url text
);
create table public.engblogs_posts (
 id bigint generated by default as identity primary key,
 created_at timestamptz default now(), published_at date, summary text, full_text text, title text, link text,
 buzzwords text[], description text, company text references public.engblogs_links(company)
);
create index engblogs_search_index on public.engblogs_posts using gin(to_tsvector('english',full_text));
create table public.engblogs_upvotes (
 id bigint generated by default as identity primary key, created_at timestamptz not null default now(), post_id bigint, ip_address cidr
);
alter table public.engblogs_links enable row level security;
alter table public.engblogs_posts enable row level security;
alter table public.engblogs_upvotes enable row level security;
revoke all on public.engblogs_upvotes from public, anon, authenticated, service_role;
revoke all on public.engblogs_links, public.engblogs_posts from public, anon, authenticated;
grant select on public.engblogs_posts to anon, authenticated;
grant select(company,logo_url) on public.engblogs_links to anon, authenticated;
create policy engblogs_read_posts on public.engblogs_posts for select to anon, authenticated using (true);
create policy engblogs_read_companies on public.engblogs_links for select to anon, authenticated using (true);
grant all on public.engblogs_links,public.engblogs_posts to service_role;
grant usage,select on sequence public.engblogs_links_id_seq,public.engblogs_posts_id_seq to service_role;
